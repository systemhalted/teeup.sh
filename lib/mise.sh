TEEUP_MISE_EXEC_SCRIPT_TOOLS="${TEEUP_MISE_EXEC_SCRIPT_TOOLS:-}"

# mise_installs_dir -> where mise keeps installed versions, resolved the way
# mise resolves its data root.
mise_installs_dir() {
  printf '%s/installs\n' "${MISE_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/mise}"
}

# local_bin_on_path: puts ~/.local/bin first on PATH for this process, as
# capabilities/zsh/default/env does for every shell. bin/teeup and bootstrap
# call it so a capability script sees the links mise_tool_install writes
# even from a Terminal the shell layer has not set up yet. An entry further
# down is moved to the front rather than kept, because pkg_backend_path
# prepends the package manager's directories and is called again later (by
# cmd_lazy_run and mise_tools_apply), each time followed by this.
local_bin_on_path() {
  local dir="$HOME/.local/bin" rest entry others=""
  case "$PATH" in
    "$dir"|"$dir":*) return 0 ;;
  esac
  if [[ -z "$PATH" ]]; then
    PATH="$dir"; export PATH
    return 0
  fi
  rest="$PATH:"
  while [[ -n "$rest" ]]; do
    entry="${rest%%:*}"
    rest="${rest#*:}"
    if [[ "$entry" != "$dir" ]]; then
      others="$others:$entry"
    fi
  done
  PATH="$dir$others"; export PATH
}

# _mise_plain_names <caller> <name...>: every name is a plain tool or
# command name, or an error names the caller and the name.
_mise_plain_names() {
  local caller="$1" t
  shift
  for t in "$@"; do
    if ! [[ "$t" =~ ^[A-Za-z0-9][A-Za-z0-9_.+-]*$ ]]; then
      err "$caller: '$t' is not a plain tool or command name"
      return 1
    fi
  done
}

# _mise_tool_wants_script <tool> -> 0 when <tool> is in
# TEEUP_MISE_EXEC_SCRIPT_TOOLS.
_mise_tool_wants_script() {
  case " $TEEUP_MISE_EXEC_SCRIPT_TOOLS " in
    *" $1 "*) return 0 ;;
  esac
  return 1
}

# _mise_tool_script <bin> -> the exec script for <bin>, single-quoted for sh.
_mise_tool_script() {
  local quoted
  quoted="$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
  printf '#!/bin/sh\n%s\nexec '\''%s'\'' "$@"\n' "$TEEUP_MISE_TOOL_MARKER" "$quoted"
}

# teeup's own directory for its mise tools: one entry per command, a
# symlink to the pinned binary (or, for a tool in
# TEEUP_MISE_EXEC_SCRIPT_TOOLS, the exec script above). Only teeup writes
# here. ~/.local/bin/<command> is a symlink to the entry, so who owns the
# ~/.local/bin path is a fact on disk: it is teeup's exactly when it points
# here. A symlink straight into mise's installs directory says nothing about
# who made it (a user's `mise use -g` setup can make the same one), so it is
# the user's. That also covers such a link from before the two-hop layout:
# that layout never shipped in a release, so no migration takes it over.
TEEUP_MISE_TOOLS_DIR="${TEEUP_MISE_TOOLS_DIR:-$TEEUP_STATE_DIR/tools}"

# _mise_tool_inner <command> -> teeup's own entry for <command>.
_mise_tool_inner() {
  printf '%s/%s\n' "$TEEUP_MISE_TOOLS_DIR" "$1"
}

# mise_tool_link_owned <path> -> 0 when <path> (~/.local/bin/<command>) is
# teeup's: a symlink whose target is exactly teeup's own entry for
# <command>, dangling or not. Anything else at the path is the user's.
mise_tool_link_owned() {
  local path="$1"
  [[ -L "$path" && "$(readlink "$path")" == "$(_mise_tool_inner "${path##*/}")" ]]
}

# mise_tool_used <command> -> 0 when teeup uses the tool behind <command>:
# ~/.local/bin/<command> is teeup's link, or it is missing and teeup's own
# entry still exists (the user deleted the link; a retry after a failed
# uninstall). Anything else at the ~/.local/bin path makes the tool the
# user's, even with an entry of teeup's left over. This, not a record,
# decides whether `teeup remove --packages` may uninstall the version.
mise_tool_used() {
  local inner link="$HOME/.local/bin/$1"
  if [[ -e "$link" || -L "$link" ]] && ! mise_tool_link_owned "$link"; then
    return 1
  fi
  inner="$(_mise_tool_inner "$1")"
  if [[ -e "$inner" || -L "$inner" ]]; then
    return 0
  fi
  mise_tool_link_owned "$HOME/.local/bin/$1"
}

# mise_tool_versions <tool> -> the version(s) of <tool> teeup uses, one per
# line: the version conf.d/teeup.toml pins, then the lock's when it differs.
# They differ when a bumped pin's download failed and the old pin was
# carried forward (mise_tools_conf_write). Without a conf.d line, the lock's
# version alone. Fails when the lock has no line for <tool>. A caller checks
# which of them mise actually has installed.
mise_tool_versions() {
  local tool="$1" version spec conf_version
  version="$(tools_lock_version "$tool")" || return 1
  spec="$(tools_lock_spec "$tool")"
  conf_version="$(_mise_tools_conf_version "$spec")"
  if [[ -n "$conf_version" && "$conf_version" != "$version" ]]; then
    printf '%s\n' "$conf_version"
  fi
  printf '%s\n' "$version"
}

# _mise_tool_inner_remove <command>: deletes teeup's own entry for
# <command>, and teeup's directory once it is empty. A dry run only says so.
_mise_tool_inner_remove() {
  local inner
  inner="$(_mise_tool_inner "$1")"
  if [[ ! -e "$inner" && ! -L "$inner" ]]; then
    return 0
  fi
  if ! run_cmd rm -f "$inner"; then
    warn "Could not remove $inner. Fix its permissions and try again."
    return 1
  fi
  if [[ "$DRY_RUN" != "true" ]]; then
    rmdir "$TEEUP_MISE_TOOLS_DIR" 2>/dev/null || true
  fi
}

# mise_tool_link_is <path> <bin> -> 0 when <path> (teeup's own entry for a
# command) already runs <bin>.
mise_tool_link_is() {
  local path="$1" bin="$2"
  if [[ -L "$path" ]]; then
    if [[ "$(readlink "$path")" == "$bin" ]]; then return 0; fi
    return 1
  fi
  if [[ -f "$path" && "$(cat "$path")" == "$(_mise_tool_script "$bin")" ]]; then
    return 0
  fi
  return 1
}

# mise_tool_install <tool> <command>
# Installs <tool> at the version share/teeup/tools.lock pins (only when that
# version is not installed yet), asks mise where its <command> is, points
# teeup's own entry for <command> at it, and links ~/.local/bin/<command> to
# that entry. A call then runs the binary directly, with no mise process in
# between. A lock bump re-points only the entry. A file or link at the
# ~/.local/bin path that is not teeup's is kept, with a warning, as
# mise_wrapper_write does; no entry is made for it, and a stale one is
# dropped. The previous version
# stays installed; `mise prune` removes it once nothing pins it.
# TEEUP_CAP names the capability in the repair hints when it is set.
# 0 linked, already linked, kept, or previewed; 1 <command> is missing.
mise_tool_install() {
  local tool="$1" command="$2" version spec link inner bin owner
  _mise_plain_names mise_tool_install "$tool" "$command" || return 1
  if ! version="$(tools_lock_version "$tool")"; then
    err "mise_tool_install: $tool has no line in $TEEUP_TOOLS_LOCK"
    return 1
  fi
  spec="$(tools_lock_spec "$tool")"
  link="$HOME/.local/bin/$command"
  inner="$(_mise_tool_inner "$command")"
  owner="${TEEUP_CAP:-<capability>}"
  if [[ -e "$link" || -L "$link" ]] && ! mise_tool_link_owned "$link"; then
    warn "Keeping $link: it was not written by teeup, so $command is not the pinned $tool $version. Remove it, then run: teeup configure $owner"
    # An entry teeup made before the user put their own file there is stale.
    _mise_tool_inner_remove "$command" || true
    return 0
  fi
  if ! have mise; then
    if [[ "$DRY_RUN" == "true" ]]; then
      run_cmd mise -C / install "$spec@$version"
      printf "%b %s\n" "🔍" "[DRY-RUN] Would link $link to $tool $version (mise)"
      return 0
    fi
    warn "mise is not on PATH, so $tool $version was not installed and $command is missing. Run: teeup install mise, then: teeup configure $owner"
    return 1
  fi
  if ! mise -C / where "$spec@$version" >/dev/null 2>&1; then
    if ! run_cmd mise -C / install "$spec@$version"; then
      warn "mise could not install $tool $version, so $command is missing. Fix the cause above, then run: teeup configure $owner"
      return 1
    fi
    if [[ "$DRY_RUN" == "true" ]]; then
      printf "%b %s\n" "🔍" "[DRY-RUN] Would link $link to $tool $version (mise)"
      return 0
    fi
  fi
  if ! bin="$(mise -C / which --tool "$spec@$version" "$command" 2>/dev/null)" || [[ -z "$bin" || ! -x "$bin" ]]; then
    warn "mise installed $tool $version, but it has no $command, so $link was not written."
    return 1
  fi
  if mise_tool_link_is "$inner" "$bin" && mise_tool_link_owned "$link"; then
    log "Already linked: $command ($tool $version)"
    return 0
  fi
  if ! mise_tool_link_is "$inner" "$bin"; then
    if [[ ! -d "$TEEUP_MISE_TOOLS_DIR" ]]; then
      run_cmd mkdir -p "$TEEUP_MISE_TOOLS_DIR" || return 1
    fi
    if _mise_tool_wants_script "$tool"; then
      # write_managed_file refuses to write through a symlink.
      if [[ -L "$inner" ]]; then
        run_cmd rm -f "$inner" || return 1
      fi
      _mise_tool_script "$bin" | write_managed_file "$inner" "$command, which runs $tool $version" || return 1
      if [[ "$DRY_RUN" != "true" ]]; then
        chmod 755 "$inner"
      fi
    elif ! run_cmd ln -sfn "$bin" "$inner"; then
      warn "Could not link $inner to $bin. Fix the permissions of $TEEUP_MISE_TOOLS_DIR, then run: teeup configure $owner"
      return 1
    fi
  fi
  if ! mise_tool_link_owned "$link"; then
    if [[ ! -d "$HOME/.local/bin" ]]; then
      run_cmd mkdir -p "$HOME/.local/bin" || return 1
    fi
    if ! run_cmd ln -sfn "$inner" "$link"; then
      warn "Could not link $link to $inner. Fix the permissions of $HOME/.local/bin, then run: teeup configure $owner"
      return 1
    fi
  fi
  ok_unless_dry "Linked $command to $tool $version (mise)"
}

# mise_tool_remove <tool> <command> [true|false]
# Removes ~/.local/bin/<command> when it is teeup's link; a foreign file or
# link stays, with a warning. Without packages, teeup's own entry for
# <command> goes too. With true (`teeup remove`, `teeup uninstall
# --packages`) it also uninstalls the version(s) teeup uses
# (mise_tool_versions) that mise has installed, and deletes the entry only
# after that worked: on a failure the entry stays, so a retry still knows
# teeup used the tool. `mise uninstall` never runs for a tool teeup does not
# use (mise_tool_used): with a foreign file at the path, the version is not
# teeup's to take away, and a leftover entry of teeup's is dropped. The conf.d file is
# the caller's to rewrite (cap_remove does it once per capability).
# 0 removed or nothing to do; 1 something that should be gone is still there.
mise_tool_remove() {
  local tool="$1" command="$2" with_packages="${3:-false}" link version spec v rc=0 used=false
  _mise_plain_names mise_tool_remove "$tool" "$command" || return 1
  link="$HOME/.local/bin/$command"
  # Asked before the link goes: an owned link is one way teeup used it.
  if mise_tool_used "$command"; then
    used=true
  fi
  if [[ -e "$link" || -L "$link" ]]; then
    if mise_tool_link_owned "$link"; then
      if ! run_cmd rm -f "$link"; then
        warn "Could not remove $link. Fix its permissions and try again."
        return 1
      fi
      if [[ "$DRY_RUN" != "true" && ( -e "$link" || -L "$link" ) ]]; then
        warn "$link is still there. Remove it and try again."
        return 1
      fi
      ok_unless_dry "Removed the link: $command"
    else
      warn "Keeping $link: it was not written by teeup."
    fi
  fi
  if [[ "$with_packages" != "true" ]]; then
    _mise_tool_inner_remove "$command"
    return $?
  fi
  if ! version="$(tools_lock_version "$tool")"; then
    log "$TEEUP_TOOLS_LOCK has no line for $tool, so no pinned version of it is uninstalled."
    _mise_tool_inner_remove "$command"
    return $?
  fi
  if [[ "$used" != "true" ]]; then
    log "Keeping $tool $version: teeup did not link $command, so it leaves the version installed."
    _mise_tool_inner_remove "$command"
    return $?
  fi
  spec="$(tools_lock_spec "$tool")"
  if ! have mise; then
    if [[ "$DRY_RUN" == "true" ]]; then
      for v in $(mise_tool_versions "$tool"); do
        run_cmd mise -C / uninstall "$spec@$v"
      done
      _mise_tool_inner_remove "$command"
      return $?
    fi
    warn "mise is not on PATH, so $tool $version stays installed. Once mise is back, run: mise uninstall $spec@$version"
    return 1
  fi
  for v in $(mise_tool_versions "$tool"); do
    if ! mise -C / where "$spec@$v" >/dev/null 2>&1; then
      log "Not installed through mise, so nothing to uninstall: $tool $v"
      continue
    fi
    if ! run_cmd mise -C / uninstall "$spec@$v"; then
      warn "Could not uninstall $tool $v through mise. Run: mise uninstall $spec@$v"
      rc=1
      continue
    fi
    ok_unless_dry "Uninstalled $tool $v (mise)"
  done
  if [[ $rc -ne 0 ]]; then
    return $rc
  fi
  _mise_tool_inner_remove "$command"
}

# mise_tools_apply <capability>
# What a capability's install runs for its mise_tools pairs: install and
# link each one, then rewrite conf.d with this capability counted as
# installed. Installing first lets mise_tools_conf_write see which versions
# are on disk: one that failed to download is never pinned, so `mise
# activate` does not warn about it in every shell. A
# mise the package manager installed earlier in this run is found even
# before the shell layer puts its prefix on PATH.
# 0 every tool linked; 1 otherwise (the warnings say which).
mise_tools_apply() {
  local cap="$1" pair cmds="" rc=0
  for pair in $(cap_meta_get "$cap" mise_tools); do
    cmds="${cmds:+$cmds }${pair#*:}"
  done
  if [[ -z "$cmds" ]]; then
    return 0
  fi
  if cap_skipped mise; then
    warn "mise is skipped on this machine (TEEUP_SKIP), so teeup does not install $cmds for $cap. Install them another way, or take mise out of TEEUP_SKIP."
    return 1
  fi
  pkg_backend_path
  local_bin_on_path
  for pair in $(cap_meta_get "$cap" mise_tools); do
    if ! TEEUP_CAP="$cap" mise_tool_install "${pair%%:*}" "${pair#*:}"; then
      rc=1
    fi
  done
  if ! mise_tools_conf_write --with "$cap"; then
    rc=1
  fi
  return $rc
}

# mise_tools_repair <capability>
# What a capability's configure runs: `teeup configure <cap>` is the repair
# path for a missing pinned version or a broken link. A failure is a warning,
# so the rest of configure still runs. Silent when mise is skipped: install
# already said so.
mise_tools_repair() {
  local cap="$1"
  if cap_skipped mise; then
    return 0
  fi
  if ! mise_tools_apply "$cap"; then
    warn "Some of $cap's tools from mise are missing or not linked (the lines above say why). Fix that, then run: teeup configure $cap"
  fi
  return 0
}

# mise_tools_sync
# `teeup update`'s pinned-tools step and the migration's whole job: every
# installed, unskipped capability's tools installed and linked at the
# versions the lock names now, lazy capabilities included (update never runs
# their configure). A tool whose pin changed gets the new version; the old
# one stays for `mise prune`. conf.d is rewritten last.
# 0 everything linked or nothing to do; 1 otherwise.
mise_tools_sync() {
  local name pair rc=0 any=false
  if cap_skipped mise; then
    log "mise is skipped on this machine (TEEUP_SKIP), so the tools teeup pins are left as they are."
    return 0
  fi
  for name in $(cap_list); do
    if state_done check "cap-$name" && ! cap_skipped "$name" && [[ -n "$(cap_meta_get "$name" mise_tools)" ]]; then
      any=true
    fi
  done
  if [[ "$any" != "true" ]]; then
    mise_tools_conf_write
    return $?
  fi
  pkg_backend_path
  local_bin_on_path
  if [[ "$DRY_RUN" != "true" ]] && ! have mise; then
    warn "mise is not on PATH, so the tools teeup pins were not checked. Run: teeup install mise, then: teeup update"
    return 1
  fi
  for name in $(cap_list); do
    if ! state_done check "cap-$name"; then continue; fi
    if cap_skipped "$name"; then
      log "Skipping $name's tools from mise (TEEUP_SKIP)"
      continue
    fi
    for pair in $(cap_meta_get "$name" mise_tools); do
      if ! TEEUP_CAP="$name" mise_tool_install "${pair%%:*}" "${pair#*:}"; then
        rc=1
      fi
    done
  done
  if ! mise_tools_conf_write; then
    rc=1
  fi
  return $rc
}

# mise_tool_old_packages <tool> -> the package names this backend knew
# <tool> by when teeup 0.3.0-beta and older installed it there, for doctor's
# old-copy notice. Homebrew's tldr formula and MacPorts' tealdeer port both
# gave the `tldr` command; git-delta gave `delta` on both.
mise_tool_old_packages() {
  case "$(pkg_backend):$1" in
    homebrew:delta|macports:delta) echo "git-delta" ;;
    homebrew:tealdeer) echo "tldr tealdeer" ;;
    *) echo "$1" ;;
  esac
}

# mise_tool_old_package_uninstall <pkg> -> the command that removes <pkg>.
mise_tool_old_package_uninstall() {
  case "$(pkg_backend)" in
    homebrew) printf 'brew uninstall %s\n' "$1" ;;
    macports) printf 'sudo port uninstall %s\n' "$1" ;;
  esac
}
